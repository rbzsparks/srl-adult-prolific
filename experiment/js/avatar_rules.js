/* avatar_rules.js: how the unfamiliar person and the face-test foils are derived from a feature vector.
 * Agreed in design/avatar_style_sheet.html (sections 3–5).
 *
 * Unfamiliar person: copies the group features (skin lightness and undertone, age and grey, lid type, iris colour,
 * freckles, hair texture and length, head covering, facial hair present/absent), moves AVATAR_UNFAM_K randomly chosen
 * identity sliders by ±AVATAR_UNFAM_STEP (direction flipped at a bound), and makes 3 categorical changes, each visible
 * at scene size:
 *   hair visible      hair style from the similar-style list (same length and texture), a different shirt colour,
 *                     and either a hair-colour change of 1..AVATAR_UNFAM_COLOUR_MAX_STEPS steps or glasses on/off
 *   head covering     covering colour, shirt colour, glasses on/off
 *   bald + facial hr  facial hair style (stays present), shirt colour, glasses on/off
 *   bald, no facial   shirt colour, glasses on/off, and one more identity slider (AVATAR_UNFAM_K_BALD_NO_FACIAL_HAIR)
 * Foils: fixed in experiment/stimuli/stimuli.json, generated by tools/make_foils.html with makeFoil() and checked
 * with checkFoils(). */
SRL.avatarRules = (function () {
  const P = SRL.people;

  const ID_SLIDERS = ['faceW', 'jaw', 'eyeSize', 'eyeTilt', 'eyeSpacing', 'noseW', 'noseL', 'lipFull', 'mouthW', 'browThick', 'browArch'];

  /* Natural hair colours as an ordered scale: black – dark brown – brown – light brown – blonde, with auburn next to
   * brown. Values are positions on the hair-colour slider. Grey is an age cue: copied, never changed, and colour
   * changes are skipped when grey (> 0.5) would hide them. */
  const HAIR_NAMED = { black: 0, darkbrown: 0.2, brown: 0.4, lightbrown: 0.58, auburn: 0.72, blonde: 0.92 };
  const HAIR_LABEL = { black: 'black', darkbrown: 'dark brown', brown: 'brown', lightbrown: 'light brown', auburn: 'auburn', blonde: 'blonde' };
  const COLOUR_ADJ = { black: ['darkbrown'], darkbrown: ['black', 'brown'], brown: ['darkbrown', 'lightbrown', 'auburn'], lightbrown: ['brown', 'blonde'], blonde: ['lightbrown'], auburn: ['brown'] };
  const namedColour = (v) => Object.keys(HAIR_NAMED).reduce((b, k) => (Math.abs(HAIR_NAMED[k] - v) < Math.abs(HAIR_NAMED[b] - v) ? k : b), 'black');
  function colourSteps(from) {
    const d = { [from]: 0 }, queue = [from];
    while (queue.length) { const c = queue.shift(); for (const n of COLOUR_ADJ[c]) if (d[n] === undefined) { d[n] = d[c] + 1; queue.push(n); } }
    return d;
  }

  /* Similar-outline styles. Never to or from bald. */
  const SIMILAR = { buzz: ['crop', 'coils_short', 'curly_short'], crop: ['sidepart', 'buzz'], sidepart: ['crop'], curly_short: ['coils_short', 'buzz'], coils_short: ['curly_short', 'buzz'],
    bangs: ['shoulder', 'bob'], bob: ['bangs', 'shoulder'], shoulder: ['bangs', 'bob', 'long'], long: ['shoulder'], curly_mid: ['afro', 'curly_long'], afro: ['curly_mid'], curly_long: ['curly_mid'], braids: ['locs'], locs: ['braids'], bun: [] };
  const FACIAL_SWAP = { stubble: 'beard', mustache: 'beard', beard: 'mustache', fullbeard: 'mustache' };
  const fitsTex = (p, s) => s !== 'bald' && P.STYLES[s].tex.includes(p.texture);
  const fits = (p, s) => fitsTex(p, s) && P.STYLES[s].len.includes(p.length);

  const pick = (a, r) => a[Math.floor(r() * a.length)];
  function shuffle(a, r) { for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(r() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; }
  const clamp01 = (v) => Math.max(0, Math.min(1, v));

  function moveIdentity(p, K, step, r) {
    const q = Object.assign({}, p), moves = {};
    for (const k of shuffle(ID_SLIDERS.slice(), r).slice(0, K)) {
      let dir = r() < 0.5 ? -1 : 1, v = p[k] + dir * step;
      if (v < 0 || v > 1) { dir = -dir; v = p[k] + dir * step; }
      q[k] = clamp01(v); moves[k] = q[k] - p[k];
    }
    return { q, moves };
  }
  const distance = (moves) => Math.sqrt(Object.values(moves).reduce((s, d) => s + d * d, 0));

  /* known: feature vector; seed: integer (the participant seed), so the result can be regenerated exactly.
   * cfg: SRL_CONFIG (AVATAR_* values). Returns { spec, moves, changes, K, distance }. */
  function unfamiliar(known, seed, cfg) {
    const r = P.rng((seed ^ 0x5EED1) >>> 0), plan = [];
    let K = cfg.AVATAR_UNFAM_K;
    if (known.covering !== 'none') plan.push('covering colour', 'shirt colour', 'glasses');
    else if (known.hairStyle === 'bald') {
      if (known.facial !== 'none') plan.push('facial hair style', 'shirt colour', 'glasses');
      else { plan.push('shirt colour', 'glasses'); K = cfg.AVATAR_UNFAM_K_BALD_NO_FACIAL_HAIR; }
    } else plan.push('hair style', 'shirt colour', pick(known.hairGray <= 0.5 ? ['hair colour', 'glasses'] : ['glasses'], r));
    const { q, moves } = moveIdentity(known, K, cfg.AVATAR_UNFAM_STEP, r);
    const changes = [];
    for (const c of plan) {
      if (c === 'hair style') {
        const similar = SIMILAR[known.hairStyle] || [];
        let opts = similar.filter((s) => fits(known, s));
        if (!opts.length) {
          // Long straight / wavy hair has no other long style on the list: allow shoulder length (agreed exception).
          const cross = similar.filter((s) => fitsTex(known, s));
          if (cross.length) { opts = cross; }
          else opts = Object.keys(P.STYLES).filter((s) => s !== known.hairStyle && fits(known, s));
        }
        q.hairStyle = pick(opts, r);
        if (!P.STYLES[q.hairStyle].len.includes(q.length)) q.length = P.STYLES[q.hairStyle].len[0];
        changes.push(`hairStyle:${known.hairStyle}>${q.hairStyle}`);
      }
      if (c === 'hair colour') {
        const from = namedColour(known.hairColor), d = colourSteps(from);
        const to = pick(Object.keys(d).filter((k) => d[k] >= 1 && d[k] <= cfg.AVATAR_UNFAM_COLOUR_MAX_STEPS), r);
        q.hairColor = HAIR_NAMED[to]; changes.push(`hairColor:${from}>${to}`);
      }
      if (c === 'glasses') { q.glasses = known.glasses === 'none' ? pick(['round', 'rect'], r) : 'none'; changes.push(`glasses:${known.glasses}>${q.glasses}`); }
      if (c === 'shirt colour') { q.shirt = pick(Object.keys(P.DESIGNER_SHIRTS).filter((x) => x !== known.shirt), r); changes.push(`shirt:${known.shirt}>${q.shirt}`); }
      if (c === 'covering colour') { q.coverColor = pick(Object.keys(P.COVER).filter((x) => x !== known.coverColor), r); changes.push(`coverColor:${known.coverColor}>${q.coverColor}`); }
      if (c === 'facial hair style') { q.facial = FACIAL_SWAP[known.facial]; changes.push(`facial:${known.facial}>${q.facial}`); }
    }
    return { spec: q, moves, changes, K, distance: distance(moves) };
  }

  /* Foil for one stranger: FOIL_K identity sliders moved by FOIL_STEP, plus one hand-picked hair change
   * (change = ['style', <style>] or ['colour', <named colour>]). */
  function makeFoil(stranger, change, seed, cfg) {
    const r = P.rng(seed), { q, moves } = moveIdentity(stranger, cfg.FOIL_K, cfg.FOIL_STEP, r), [kind, to] = change;
    if (kind === 'style') { q.hairStyle = to; if (!P.STYLES[to].len.includes(q.length)) q.length = P.STYLES[to].len[0]; }
    else q.hairColor = HAIR_NAMED[to];
    return { spec: q, moves, distance: distance(moves) };
  }

  /* The six foil rules. sets: [{ stranger: {id, gender, ...vector}, foil_change: [kind, to] }] in scene-set order
   * (first 6 = half 1). Returns [[ok, text], ...]. */
  function checkFoils(sets) {
    const S = sets.map((s) => s.stranger), F = sets.map((s) => s.foil_change);
    const worn = { style: new Set(S.map((s) => s.hairStyle)), colour: new Set(S.map((s) => namedColour(s.hairColor))) };
    const out = [];
    const notWorn = S.filter((s, i) => !worn[F[i][0]].has(F[i][1])).map((s) => s.id);
    out.push([!notWorn.length, 'Every foil\'s new style or colour is also worn by a stranger' + (notWorn.length ? ' (not: ' + notWorn.join(', ') + ')' : '')]);
    const use = {}; F.forEach(([k, t]) => { if (k === 'style') use[t] = (use[t] || 0) + 1; });
    out.push([Object.values(use).every((n) => n <= 2), 'Each target style used by at most 2 foils (' + Object.entries(use).map(([k, n]) => k + ' ' + n).join(', ') + ')']);
    const h = [0, 1].map((x) => F.filter((c, i) => (i < 6 ? 0 : 1) === x && c[0] === 'style').length);
    out.push([h[0] === 3 && h[1] === 3, `Style changes per half: ${h[0]} and ${h[1]} (3 each)`]);
    const gw = S.filter((s, i) => s.gender === 'f' && F[i][0] === 'style').length, gm = S.filter((s, i) => s.gender === 'm' && F[i][0] === 'style').length;
    out.push([gw === 3 && gm === 3, `Style changes by gender: women ${gw}, men ${gm} (3 each)`]);
    const sim = S.filter((s, i) => F[i][0] === 'style' && !(SIMILAR[s.hairStyle] || []).includes(F[i][1])).map((s) => s.id);
    out.push([!sim.length, 'Style targets come from the similar-style list' + (sim.length ? ' (not: ' + sim.join(', ') + ')' : '')]);
    const bad = S.filter((s, i) => F[i][0] === 'colour' && (colourSteps(namedColour(s.hairColor))[F[i][1]] !== 1 || s.hairGray > 0.5)).map((s) => s.id);
    out.push([!bad.length, 'Colour changes are one step and never on grey hair' + (bad.length ? ' (not: ' + bad.join(', ') + ')' : '')]);
    return out;
  }

  /* Repeat-6 foil rules. stim = stimuli_repeat6.json. Entries of each stranger set are in scene-set order; entries
   * 0/1, 2/3, 4/5 are the matched pairs (first-listed member in the odd scene set = known in list A). */
  function checkFoilsRepeat6(stim) {
    const out = [];
    const all = [];
    Object.keys(stim.stranger_sets).forEach((k) => stim.stranger_sets[k].forEach((e) => all.push(e.stranger)));
    const worn = { style: new Set(all.map((s) => s.hairStyle)), colour: new Set(all.map((s) => namedColour(s.hairColor))) };
    const grey = (s) => s.hairGray > 0.5;
    Object.keys(stim.stranger_sets).forEach((k) => {
      const E = stim.stranger_sets[k], pairs = [[E[0], E[1]], [E[2], E[3]], [E[4], E[5]]];
      const match = pairs.every(([a, b]) => a.stranger.gender === b.stranger.gender && a.stranger.age === b.stranger.age);
      out.push([match, `Set ${k}: each pair matches on gender presentation and age band`]);
      const typesOk = pairs.every(([a, b]) => (grey(a.stranger) && grey(b.stranger))
        ? a.foil_change[0] === 'style' && b.foil_change[0] === 'style'
        : a.foil_change[0] !== b.foil_change[0]);
      out.push([typesOk, `Set ${k}: one style + one colour foil per pair (both style when both have grey hair): ` + pairs.map(([a, b]) => a.foil_change[0] + '/' + b.foil_change[0]).join(', ')]);
      const mixed = pairs.filter(([a, b]) => a.foil_change[0] !== b.foil_change[0]).map(([a]) => a.foil_change[0]);
      let alt = true; for (let i = 1; i < mixed.length; i++) if (mixed[i] === mixed[i - 1]) alt = false;
      out.push([alt, `Set ${k}: first-listed member's foil type alternates across mixed pairs (${mixed.join(', ')})`]);
      const cond = [0, 1].map((x) => [x, x + 2, x + 4].map((i) => E[i].foil_change[0]));
      out.push([cond.every((c) => c.indexOf('style') >= 0 && c.indexOf('colour') >= 0), `Set ${k}: each condition gets both foil types (odd: ${cond[0].join(', ')}; even: ${cond[1].join(', ')})`]);
      const use = {}; E.forEach((e) => { if (e.foil_change[0] === 'style') use[e.foil_change[1]] = (use[e.foil_change[1]] || 0) + 1; });
      out.push([Object.keys(use).every((t) => use[t] <= 2), `Set ${k}: each target style used by at most 2 foils`]);
    });
    const ents = []; Object.keys(stim.stranger_sets).forEach((k) => stim.stranger_sets[k].forEach((e) => ents.push(e)));
    const nw = ents.filter((e) => !worn[e.foil_change[0]].has(e.foil_change[1])).map((e) => e.stranger.id);
    out.push([!nw.length, 'Every new style or colour is also worn by a stranger' + (nw.length ? ' (not: ' + nw.join(', ') + ')' : '')]);
    const sim = ents.filter((e) => e.foil_change[0] === 'style' && !(SIMILAR[e.stranger.hairStyle] || []).includes(e.foil_change[1])).map((e) => e.stranger.id);
    out.push([!sim.length, 'Style targets come from the similar-style list' + (sim.length ? ' (not: ' + sim.join(', ') + ')' : '')]);
    const bad = ents.filter((e) => e.foil_change[0] === 'colour' && (colourSteps(namedColour(e.stranger.hairColor))[e.foil_change[1]] !== 1 || grey(e.stranger))).map((e) => e.stranger.id);
    out.push([!bad.length, 'Colour changes are one step and never on grey hair' + (bad.length ? ' (not: ' + bad.join(', ') + ')' : '')]);
    return out;
  }

  return { ID_SLIDERS, HAIR_NAMED, HAIR_LABEL, SIMILAR, namedColour, colourSteps, moveIdentity, unfamiliar, makeFoil, checkFoils, checkFoilsRepeat6, distance };
})();
