"""Build experiment/stimuli/stimuli_repeat6.json from stimuli.json (the unique12 file is not changed).

Repeat-6 design: 6 scene sets (ss1-ss6), each with a fixed object + word and incidental object type; the stranger
for each scene set depends on the stranger set (X or Y). Strangers, frozen foils and voices are copied from
stimuli.json; the two foil changes listed in FOIL_OVERRIDES are new, and their foils are regenerated by
tools/make_foils.html?design=repeat6 (which also checks the repeat-6 foil rules).
Run:  python tools/build_repeat6_stimuli.py   then open tools/make_foils.html?design=repeat6 through the dev server and save.
"""
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
SRC = os.path.join(ROOT, 'experiment', 'stimuli', 'stimuli.json')
OUT = os.path.join(ROOT, 'experiment', 'stimuli', 'stimuli_repeat6.json')

# id, half (1 = known in list A), word, drawing (object_id = the drawing shown), incidental type
SCENE_SETS = [
    ('ss1', 1, 'bosa', 'obj_bosa', 'mug'),
    ('ss2', 2, 'daxa', 'obj_daxa', 'vase'),
    ('ss3', 1, 'lufi', 'obj_zibu', 'lamp'),    # cube drawing, labelled lufi in repeat6
    ('ss4', 2, 'tefo', 'obj_tefo', 'clock'),
    ('ss5', 1, 'mavo', 'obj_fiku', 'book'),    # teal blob drawing, labelled mavo in repeat6
    ('ss6', 2, 'gimu', 'obj_gimu', 'candle'),
]
# Matched pairs (same gender presentation and age band); first-listed member -> odd scene set.
STRANGER_SETS = {
    'X': ['str01', 'str07', 'str04', 'str10', 'str05', 'str11'],
    'Y': ['str02', 'str08', 'str03', 'str09', 'str06', 'str12'],
}
# Repeat6-only foil changes (colour -> style) so every young / middle-aged pair has one style and one colour foil,
# alternating which type the first-listed member has. Older pairs keep two style foils (grey hair hides colour).
FOIL_OVERRIDES = {'str02': ['style', 'locs'], 'str09': ['style', 'long']}


def main():
    d = json.load(open(SRC, encoding='utf-8'))
    by_str = {s['stranger']['id']: s for s in d['scene_sets']}
    words = [w for _, _, w, _, _ in SCENE_SETS]
    out = {
        '_comment': 'Repeat-6 design (see README). Built by tools/build_repeat6_stimuli.py; foils by tools/make_foils.html?design=repeat6.',
        'version': '1.0.0',
        'design_version': 'repeat6',
        'incidental_colors': d['incidental_colors'],
        'words': {w: d['words'][w] for w in words},
        'incidental_types': {t: d['incidental_types'][t] for _, _, _, _, t in SCENE_SETS},
        'narrator': d['narrator'],
        'scene_sets': [{'id': i, 'half': h, 'word': w, 'object_id': o, 'incidental': t} for i, h, w, o, t in SCENE_SETS],
        'stranger_sets': {},
    }
    for key, ids in STRANGER_SETS.items():
        rows = []
        for (sid, _, word, _, _), stid in zip(SCENE_SETS, ids):
            src = by_str[stid]
            n = stid[3:]
            same_word = src['word'] == word
            change = FOIL_OVERRIDES.get(stid, src['foil_change'])
            foil = dict(src['foil'])
            if stid in FOIL_OVERRIDES:
                foil['id'] = 'foil' + n + 'b'  # differs from unique12's foil of the same stranger
            rows.append({'scene_set_id': sid, 'stranger': src['stranger'], 'foil': foil, 'foil_change': change,
                         'foil_seed': src['foil_seed'], 'voice': src['voice'], 'greet_clip': 'greet_s' + n,
                         'label_clip': ('label_s' + n) if same_word else f'label_{stid}_{word}'})
        out['stranger_sets'][key] = rows
    open(OUT, 'w', encoding='utf-8', newline='\n').write(fmt(out))
    print('wrote', OUT)
    for key, rows in out['stranger_sets'].items():
        print(key, [(r['scene_set_id'], r['stranger']['id'], r['foil_change'][0], r['label_clip']) for r in rows])


def fmt(d):
    """Compact layout: one line per word / scene set / stranger-set entry object."""
    J = lambda v: json.dumps(v, ensure_ascii=False)
    top = []
    for k, v in d.items():
        if k in ('words', 'incidental_types', 'incidental_colors'):
            top.append(f'  {J(k)}: {{\n' + ',\n'.join(f'    {J(a)}: {J(b)}' for a, b in v.items()) + '\n  }')
        elif k == 'scene_sets':
            top.append(f'  {J(k)}: [\n' + ',\n'.join('    ' + J(s) for s in v) + '\n  ]')
        elif k == 'stranger_sets':
            parts = []
            for sk, rows in v.items():
                ents = []
                for r in rows:
                    simple = {a: b for a, b in r.items() if not isinstance(b, dict)}
                    objs = {a: b for a, b in r.items() if isinstance(b, dict)}
                    ents.append('      {' + J(simple)[1:-1] + ',\n' + ',\n'.join(f'       {J(a)}: {J(b)}' for a, b in objs.items()) + '}')
                parts.append(f'    {J(sk)}: [\n' + ',\n'.join(ents) + '\n    ]')
            top.append(f'  {J(k)}: {{\n' + ',\n'.join(parts) + '\n  }')
        else:
            top.append(f'  {J(k)}: {J(v)}')
    return '{\n' + ',\n'.join(top) + '\n}\n'


if __name__ == '__main__':
    main()
